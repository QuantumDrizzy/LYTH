#[test]
fn a_coalesced_kernel_pays_the_payload_and_nothing_more() {
    // Every rank-1 kernel walks its buffers at the loop index, so neighbouring threads are on
    // neighbouring elements and no sector is half wasted. If this ever drifts, the sector
    // model has started charging kernels it should not.
    for name in ["saxpy.lyth", "sum.lyth", "horner.lyth", "split.lyth", "max.lyth"] {
        let src = example(name);
        let unit = parse(&src).unwrap();
        let ir = ir::lower(&unit, &unit.kernels[0]).unwrap();
        assert_eq!(ir.cost.coalescence(), 1.0, "{name}");
        assert_eq!(
            ir.cost.sector_read_per_element + ir.cost.sector_write_per_element,
            ir.cost.bytes_per_element().unwrap(),
            "{name}: sectors and payload must agree when every access is contiguous"
        );
        assert!(ir.streams.iter().all(|s| s.coalesced), "{name}");
    }
}

#[test]
fn a_transpose_is_charged_a_sector_for_its_strided_side() {
    let src = example("transpose.lyth");
    let unit = parse(&src).unwrap();
    let ir = ir::lower(&unit, &unit.kernels[0]).unwrap();

    // `a[i, j]` innermost index is `j`, the fast variable: contiguous. `b[j, i]` is not.
    let by = |n: &str| ir.streams.iter().find(|s| s.buffer == n).unwrap().clone();
    assert!(by("a").coalesced, "a is read along its rows");
    assert!(!by("b").coalesced, "b is written down its columns");

    assert_eq!(ir.cost.bytes_per_element().unwrap(), 8.0, "the payload is unchanged");
    assert_eq!(ir.cost.sector_read_per_element, 4.0);
    assert_eq!(ir.cost.sector_write_per_element, 32.0);
    assert!((ir.cost.coalescence() - 8.0 / 36.0).abs() < 1e-12);
}

#[test]
fn the_coalescence_rule_is_about_the_fast_index_not_about_transposition() {
    // The rule is `innermost index == innermost space variable`, which is why it generalises.
    // Here both buffers are walked the same way, so nothing is strided even though the kernel
    // is rank 2 and indexes explicitly.
    let src = "machine sm_120\n\nkernel copy2d(rows: u32, cols: u32, a: [f32; rows, cols], b: [f32; rows, cols])\n    space i, j : rows, cols\n    stream a : dram -> reg\n    stream b : dram -> reg, drain\n    at reg:\n        b[i, j] = a[i, j]\n";
    let unit = parse(src).unwrap();
    let ir = ir::lower(&unit, &unit.kernels[0]).unwrap();
    assert_eq!(ir.cost.coalescence(), 1.0, "a rank-2 copy is contiguous both sides");

    // And swapping only the space's variable order makes the same source strided, because the
    // fast index moved. Nothing about the buffers changed.
    let swapped = src.replace("space i, j : rows, cols", "space j, i : cols, rows");
    let unit = parse(&swapped).unwrap();
    let ir = ir::lower(&unit, &unit.kernels[0]).unwrap();
    assert!(ir.cost.coalescence() < 1.0, "the fast variable is now `i`");
}

/// `tile` and the staged stream path: what parses, what is refused, and what the back end
/// does with a declaration it cannot honour yet (ADR-0017, step 1).
mod tile {
    use super::*;

    const TILED: &str = "machine sm_120\n\nkernel t(rows: u32, cols: u32, a: [f32; rows, cols], b: [f32; cols, rows])\n    space i, j : rows, cols\n    tile 32, 32\n    stream a : dram -> smem -> reg\n    stream b : dram -> reg, drain\n    at reg:\n        b[j, i] = a[i, j]\n";

    fn lower(src: &str) -> Result<lyth_lang::KernelIr, String> {
        let unit = parse(src).map_err(|e| e.to_string())?;
        ir::lower(&unit, &unit.kernels[0]).map_err(|e| e.to_string())
    }

    #[test]
    fn a_tiled_kernel_lowers_and_carries_its_tile_and_its_staging() {
        let ir = lower(TILED).expect("a tiled transpose should lower");
        assert_eq!(ir.tile, Some(vec![32, 32]));
        let by = |n: &str| ir.streams.iter().find(|s| s.buffer == n).unwrap().clone();
        assert!(by("a").staged, "a travels through smem");
        assert!(!by("b").staged, "b goes straight to dram");
        // Step 1 changes no cost: the bus model still sees the untiled access pattern until
        // the staged stream is modelled in step 4.
        assert_eq!(ir.cost.bytes_per_element().unwrap(), 8.0);
    }

    #[test]
    fn the_back_end_emits_the_tile_it_used_to_refuse() {
        // Step 1 refused a tile rather than compiling the flat body for it, because the cost
        // the front end derived would not have described the kernel that came out. Step 3
        // makes it describable.
        let ir = lower(TILED).unwrap();
        let m = lyth_ptx::emit(&ir, "sm_120").expect("a tile is emitted now");
        assert!(m.ptx.contains("st.shared.f32"), "it stages: {}", m.ptx);
        assert!(m.ptx.contains("ld.shared.f32"), "and reads back: {}", m.ptx);
    }

    #[test]
    fn a_tile_needs_a_space_to_block() {
        let src = "machine sm_120\n\nkernel t(n: u32, x: [f32; n], y: [f32; n])\n    tile 32, 32\n    stream x : dram -> reg\n    stream y : dram -> reg, drain\n    at reg:\n        y = x\n";
        let e = lower(src).expect_err("a tile with nothing to block");
        assert!(e.contains("declares no `space`"), "{e}");
    }

    #[test]
    fn a_tile_has_one_dimension_per_index() {
        let e = lower(&TILED.replace("tile 32, 32", "tile 32")).expect_err("rank mismatch");
        assert!(e.contains("one dimension per index"), "{e}");
    }

    #[test]
    fn a_tile_dimension_that_is_not_a_power_of_two_is_refused() {
        // Anything else needs a division per thread to find its place in the tile, which on
        // this hardware is a sequence and not an instruction (ADR-0015 measured it).
        let e = lower(&TILED.replace("tile 32, 32", "tile 30, 32")).expect_err("not a power");
        assert!(e.contains("power of two"), "{e}");
        assert!(e.contains("shift and a mask"), "{e}");
    }

    #[test]
    fn staging_without_a_tile_is_refused_and_says_both_ways_out() {
        let e = lower(&TILED.replace("    tile 32, 32\n", "")).expect_err("staged, no tile");
        assert!(e.contains("declares no `tile`"), "{e}");
        assert!(e.contains("dram -> reg"), "it names the other way out: {e}");
    }

    #[test]
    fn a_stream_path_of_one_level_moves_nothing() {
        let src = "machine sm_120\n\nkernel t(n: u32, x: [f32; n], y: [f32; n])\n    stream x : dram\n    stream y : dram -> reg, drain\n    at reg:\n        y = x\n";
        let e = lower(src).expect_err("a path needs two levels");
        assert!(e.contains("moves between levels"), "{e}");
    }
}

/// The four-phase tiled body, asserted on the emitted text (ADR-0017, step 3).
///
/// These need no GPU and they are the deterministic half of the schedule oracle: the PTX
/// cannot lie about what it contains. The launch-with-zero check catches the other case, where
/// what it contains goes unused.
mod tiled_ptx {
    use super::*;

    fn ptx(name: &str) -> String {
        compile(name).expect("the tiled transpose should compile").ptx
    }

    #[test]
    fn there_are_two_barriers_and_not_one() {
        // The loop is grid-stride over tiles, so the next tile's load races the previous
        // tile's read without a barrier after the read as well as after the write. One
        // barrier corrupts the output only sometimes, which is worse than always.
        let m = ptx("transpose-tiled.lyth");
        assert_eq!(m.matches("bar.sync 0;").count(), 2, "{m}");
        assert_eq!(m.matches(".extern .shared").count(), 1, "{m}");
    }

    #[test]
    fn the_skew_is_applied_to_both_phases() {
        // A store that uses the padded stride and a load that does not compiles, runs, and
        // produces correct bits while conflicting on every read. Only this and the
        // counterfactual fixture separate that from a correct emitter.
        let m = ptx("transpose-tiled.lyth");
        let skewed: Vec<&str> = m
            .lines()
            .filter(|l| l.contains("mad.lo.u32") && l.contains(", 33, "))
            .collect();
        assert_eq!(skewed.len(), 2, "one per phase, got: {skewed:?}
{m}");
        // And the two are transposes of each other: ty*33+tx against tx*33+ty.
        // `mad.lo.u32 %rD, %rA, 33, %rB;` -> (%rA, %rB). parts[0] ends in the destination.
        let operands = |l: &str| -> (String, String) {
            let parts: Vec<&str> = l.trim().split(", ").collect();
            (
                parts[1].to_string(),
                parts[3].trim_end_matches(';').to_string(),
            )
        };
        let (a0, a1) = operands(skewed[0]);
        let (b0, b1) = operands(skewed[1]);
        assert_eq!((a0, a1), (b1, b0), "the phases must swap the indices");
    }

    #[test]
    fn no_thread_can_branch_around_a_barrier() {
        // A thread that skipped a bar.sync while its block reached one deadlocks the block or
        // aborts the launch. So the only branch in the body is the loop exit, and its
        // predicate is on the tile index, which every thread of the block shares.
        let m = ptx("transpose-tiled.lyth");
        let branches: Vec<&str> = m.lines().filter(|l| l.contains(" bra ")).collect();
        let predicated: Vec<&&str> = branches.iter().filter(|l| l.contains("@%p")).collect();
        assert_eq!(
            predicated.len(),
            1,
            "exactly one predicated branch, the uniform loop exit: {branches:?}"
        );
        assert!(predicated[0].contains("$L_tile_end"), "{:?}", predicated[0]);
        // The boundary guards predicate instructions instead.
        assert!(m.contains("@%p") && m.contains("ld.global.f32"), "{m}");
        for l in m.lines().filter(|l| l.contains("global.f32")) {
            assert!(
                l.trim().starts_with("@%p") || l.contains("mov"),
                "a global access outside a guard: {l}"
            );
        }
    }

    #[test]
    fn the_unpadded_variant_differs_and_exists_only_for_the_counterfactual() {
        // `bank_conflicts = 0` on the padded kernel shows the conflicts are absent, not that
        // the skew removed them. The fixture that must conflict is built here.
        let src = example("transpose-tiled.lyth");
        let unit = parse(&src).unwrap();
        let ir = ir::lower(&unit, &unit.kernels[0]).unwrap();
        let padded = lyth_ptx::emit_with_skew(&ir, "sm_120", true).unwrap();
        let flat = lyth_ptx::emit_with_skew(&ir, "sm_120", false).unwrap();
        assert!(padded.ptx.contains(", 33, "), "the derived stride");
        assert!(flat.ptx.contains(", 32, "), "the unpadded one");
        assert!(!flat.ptx.contains(", 33, "), "no skew anywhere in the counterfactual");
        assert_ne!(padded.ptx, flat.ptx);
    }

    #[test]
    fn a_tile_that_stages_nothing_is_refused() {
        // It would change no traffic and derive no shared memory, so it is a declaration that
        // means nothing -- refused rather than compiled into the flat body.
        let src = example("transpose-tiled.lyth").replace("dram -> smem -> reg", "dram -> reg");
        let unit = parse(&src).unwrap();
        let ir = ir::lower(&unit, &unit.kernels[0]).unwrap();
        let e = lyth_ptx::emit(&ir, "sm_120").expect_err("a tile with nothing staged");
        assert!(e.to_string().contains("stages nothing"), "{e}");
    }
}

/// The launch shape is derived once, and the paths that launch ask for it.
///
/// This is the test the morning of 2026-09-16 did not have. `report_timing` assembled its own
/// shape from two of three fields and the 256 default, so a tiled kernel verified at 1024
/// threads was timed at 256, ran a quarter of every tile, produced results nothing checked and
/// reported 3.85 TB/s on a 358 GB/s device.
mod launch {
    use super::*;

    fn shape(src: &str, block_arg: Option<u32>) -> (u32, u32) {
        let unit = parse(src).unwrap();
        let ir = ir::lower(&unit, &unit.kernels[0]).unwrap();
        // Mirrors `launch_shape` in the binary, which is private to it. Held here so that a
        // change in one without the other fails rather than diverging quietly.
        let block: u32 = match &ir.tile {
            Some(t) => t.iter().product(),
            None => block_arg.unwrap_or(256),
        };
        let shared = match (&ir.shared, ir.reduction.is_some()) {
            (Some(l), _) => l.bytes,
            (None, true) => block * 4,
            (None, false) => 0,
        };
        (block, shared)
    }

    const TILED: &str = "machine sm_120\n\nkernel t(rows: u32, cols: u32, a: [f32; rows, cols], b: [f32; cols, rows])\n    space i, j : rows, cols\n    tile 32, 32\n    stream a : dram -> smem -> reg\n    stream b : dram -> reg, drain\n    at reg:\n        b[j, i] = a[i, j]\n";
    const FLAT: &str = "machine sm_120\n\nkernel k(n: u32, x: [f32; n], y: [f32; n])\n    stream x : dram -> reg\n    stream y : dram -> reg, drain\n    at reg:\n        y = x\n";
    const REDUCE: &str = "machine sm_120\n\nkernel s(n: u32, x: [f32; n], partial: [f32; blocks])\n    stream x : dram -> reg\n    reduce sum v : reg -> smem -> dram into partial\n    at reg:\n        v = x\n";

    #[test]
    fn a_tile_fixes_the_block_and_a_flag_cannot_move_it() {
        assert_eq!(shape(TILED, None), (1024, 4224));
        // `--block` is refused beside a tile, and if it ever were not, the tile still wins.
        assert_eq!(shape(TILED, Some(256)), (1024, 4224));
    }

    #[test]
    fn a_flat_kernel_takes_the_flag_or_the_default_and_no_shared_memory() {
        assert_eq!(shape(FLAT, None), (256, 0));
        assert_eq!(shape(FLAT, Some(128)), (128, 0));
    }

    #[test]
    fn a_reduction_sizes_its_shared_memory_by_the_block_it_actually_gets() {
        assert_eq!(shape(REDUCE, None), (256, 1024));
        assert_eq!(shape(REDUCE, Some(512)), (512, 2048));
    }
}
