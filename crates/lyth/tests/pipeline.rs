//! Source to PTX, end to end, with no GPU.
//!
//! These run the real `examples/*.lyth` files through the real pipeline, so an example that
//! stops compiling fails the build rather than being discovered by a reader. The launch and
//! the bit-exact check need a device and live in `lyth run`; everything up to the module is
//! checked here.

use std::path::PathBuf;

use lyth_lang::{ir, parse};
use lyth_ptx::emit;

fn example(name: &str) -> String {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../examples")
        .join(name);
    std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()))
}

fn compile(name: &str) -> Result<lyth_ptx::Module, String> {
    let src = example(name);
    let unit = parse(&src).map_err(|e| e.to_string())?;
    let kernel = &unit.kernels[0];
    let ir = ir::lower(&unit, kernel).map_err(|e| e.to_string())?;
    if let Some(declared) = kernel.declared_intensity {
        lyth_lang::check_intensity(&ir, Some(declared), None, 0.05).map_err(|e| e.to_string())?;
    }
    emit(&ir, "sm_120").map_err(|e| e.to_string())
}

#[test]
fn saxpy_compiles_and_moves_what_it_says() {
    let m = compile("saxpy.lyth").expect("saxpy should compile");
    assert!(m.ptx.contains(".target sm_120"));
    assert_eq!(m.entry, "saxpy");
    // 8 bytes read as two loads, 4 written as one store — the derived model, in instructions.
    assert_eq!(m.ptx.matches("ld.global.f32").count(), 2);
    assert_eq!(m.ptx.matches("st.global.f32").count(), 1);
    assert_eq!(m.ptx.matches("fma.rn.f32").count(), 1);
}

#[test]
fn an_unstaged_reduction_is_refused_by_the_gpu_back_end() {
    // ADR-0025 step 3 gave `reduce` a second legal path, `reg -> dram`, for a machine whose
    // parallelism is the lanes of one register. This back end emits the other one: it writes
    // every thread's partial to `__shared__` and folds a tree there.
    //
    // So the second path has to be refused *here*, not merely unused. Emitting the staged
    // kernel for a source that declared it unstaged would produce working PTX whose cost is
    // nothing like the one the front end derived for it -- the model would say no shared
    // traffic and the device would move 8 bytes an element.
    let src = example("sum.lyth").replace("reg -> smem -> dram", "reg -> dram");
    let unit = parse(&src).expect("parses");
    let ir = ir::lower(&unit, &unit.kernels[0]).expect("lowers -- the path is legal now");
    let e = emit(&ir, "sm_120").expect_err("but not on this machine");
    let msg = e.to_string();
    assert!(msg.contains("folds the block in shared"), "{msg}");
    assert!(msg.contains("reg -> smem"), "{msg}");
}

